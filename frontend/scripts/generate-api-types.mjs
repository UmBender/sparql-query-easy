#!/usr/bin/env node
// FE-043: regenerate src/lib/api/schema.d.ts from the OpenAPI snapshot
// src/lib/api/openapi.json (kept equal to Ktor's /openapi.json by the Kotlin
// test FrontendOpenApiSnapshotTest). openapi-typescript runs through npx at a
// pinned version because it declares a TypeScript 5 peer. The header records
// the snapshot's SHA-256; api-contract.spec.ts fails when they differ.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const snapshot = `${root}src/lib/api/openapi.json`;
const output = `${root}src/lib/api/schema.d.ts`;
const result = spawnSync('npx', ['--yes', 'openapi-typescript@7.13.0', snapshot, '-o', output], {
	stdio: 'inherit'
});
if (result.status !== 0) process.exit(result.status ?? 1);
const hash = createHash('sha256').update(readFileSync(snapshot)).digest('hex');
writeFileSync(
	output,
	`// Generated by \`npm run api:types\` from openapi.json sha256:${hash}; do not edit.\n${readFileSync(output, 'utf8')}`
);
